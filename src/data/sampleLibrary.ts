// Helper to generate deterministic waveform peaks
function generatePeaks(pattern: 'drums' | 'melodic' | 'bass' | 'fx' | 'vocal', count = 40): number[] {
  const peaks: number[] = [];
  for (let i = 0; i < count; i++) {
    let val = 0.2;
    if (pattern === 'drums') {
      // 4-on-the-floor or syncopated drum transients
      if (i % 10 === 0) val = 0.95;
      else if (i % 5 === 0) val = 0.75;
      else if (i % 2 === 0) val = 0.45;
      else val = 0.15 + Math.sin(i) * 0.1;
    } else if (pattern === 'bass') {
      val = 0.4 + 0.5 * Math.abs(Math.sin((i / count) * Math.PI * 4));
    } else if (pattern === 'melodic') {
      val = 0.3 + 0.6 * Math.abs(Math.sin((i / count) * Math.PI * 3) * Math.cos(i * 0.5));
    } else if (pattern === 'fx') {
      val = 0.1 + (i / count) * 0.85; // riser shape
    } else {
      val = 0.2 + 0.7 * Math.abs(Math.sin(i * 0.8) * Math.sin(i * 1.5));
    }
    peaks.push(Math.min(1.0, Math.max(0.08, Number(val.toFixed(2)))));
  }
  return peaks;
}

